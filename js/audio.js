  // Potion Drinking audio: bubbling sips followed by swallow
  playDrink() {
    if (!this.ctx) return;
    this.resume();
    const t = this.ctx.currentTime;

    // 3 quick bubbly sips
    for (let i = 0; i < 3; i++) {
      const sipTime = t + i * 0.085;
      const osc = this.ctx.createOscillator();
      const gain = this.ctx.createGain();

      osc.type = 'sine';
      const baseFreq = 420 + Math.random() * 80;
      osc.frequency.setValueAtTime(baseFreq, sipTime);
      osc.frequency.exponentialRampToValueAtTime(baseFreq * 0.65, sipTime + 0.06);

      gain.gain.setValueAtTime(0.22, sipTime);
      gain.gain.exponentialRampToValueAtTime(0.001, sipTime + 0.065);

      osc.connect(gain);
      gain.connect(this.ctx.destination);

      osc.start(sipTime);
      osc.stop(sipTime + 0.07);
    }

    // Finishing gulp sound
    const gulpTime = t + 0.28;
    const gulpOsc = this.ctx.createOscillator();
    const gulpGain = this.ctx.createGain();
    gulpOsc.type = 'triangle';
    gulpOsc.frequency.setValueAtTime(260, gulpTime);
    gulpOsc.frequency.exponentialRampToValueAtTime(140, gulpTime + 0.09);

    gulpGain.gain.setValueAtTime(0.28, gulpTime);
    gulpGain.gain.exponentialRampToValueAtTime(0.001, gulpTime + 0.095);

    gulpOsc.connect(gulpGain);
    gulpGain.connect(this.ctx.destination);

    gulpOsc.start(gulpTime);
    gulpOsc.stop(gulpTime + 0.1);
  }

